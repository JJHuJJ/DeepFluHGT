def main():
    m = MODELS[ARGS.model]
    if ARGS.task == "anchors":
        assert ARGS.anchor, "--anchor is required (benbow/iv4/ice/philympics)"
        run_anchor(m, ARGS)
    elif ARGS.task == "test":
        run_test(m, ARGS)
    elif ARGS.task == "ood":
        run_ood(m, ARGS)
    elif ARGS.task == "difficulty":
        assert ARGS.tier, "--tier is required (D1/D2/D3)"
        run_difficulty(m, ARGS)
    elif ARGS.task == "report":
        assert ARGS.which, "--which is required (anchors/difficulty)"
        (report_anchors if ARGS.which == "anchors" else report_difficulty)(m, ARGS)


if __name__ == "__main__":
    main()
