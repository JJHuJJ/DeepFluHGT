def report_difficulty(m: dict, args):
    out_dir = Path(args.out_dir) if args.out_dir else m["out_dir"]
    test_json = out_dir / f"test_eval_{m['tag']}.json"
    d0 = None
    if test_json.is_file():
        tj = json.load(open(test_json))
        d0 = {"auprc": tj["results"]["max"].get("auprc"),
              "auroc": tj["results"]["max"].get("auc"),
              "n_contigs": tj["window_stats"]["n_contigs"],
              "n_windows": tj["window_stats"]["n_windows"],
              "auprc_mean": tj["results"]["mean"].get("auprc"),
              "source": f"this model, same checkpoint and protocol, full pool (test_eval_{m['tag']}.json)"}

    rows = []
    for tier in ["D1", "D2", "D3"]:
        tier_dir, axis = TIERS[tier]
        jp = out_dir / f"difficulty_{tier}_{m['tag']}.json"
        if not jp.is_file():
            rows.append({"tier": tier, "axis": axis, "missing": True})
            continue
        j = json.load(open(jp))
        span = {}
        meta = ROOT / f"simulated_data/difficulty_ladder/{tier_dir}/test/metadata.json"
        if meta.is_file():
            try:
                mm = json.load(open(meta))
                pos = mm["positive"] if isinstance(mm, dict) else \
                    [x for x in mm if x.get("label") == 1]
                spans = [max(e["hgt_end"] for e in x["events"]) -
                         min(e["hgt_start"] for e in x["events"])
                         for x in pos if x.get("events")]
                a = np.array(spans)
                span = {"n_pos": len(pos), "span_p50": float(np.median(a)),
                        "span_p90": float(np.percentile(a, 90))}
            except Exception as e:
                span = {"error": str(e)}
        rows.append({
            "tier": tier, "axis": axis, "missing": False,
            "n_contigs": j["window_stats"]["n_contigs"],
            "n_windows": j["window_stats"]["n_windows"],
            "auprc_max": j["results"]["max"].get("auprc"),
            "auroc_max": j["results"]["max"].get("auc"),
            "auprc_mean": j["results"]["mean"].get("auprc"),
            "auprc_top3": j["results"]["top3_mean"].get("auprc"),
            "f1_max": j["results"]["max"].get("f1_at_optimal"),
            "delong_max": j["delong"]["max"], "span": span,
            "evo_hit": j.get("evo", {}).get("contigs_cache_hit"),
            "evo_total": j.get("evo", {}).get("contigs_total"),
        })

    md = []
    md.append(f"> **{m['header']}**\n\n")
    md.append(f"# Difficulty ladder D0-D3  -  {m['name']} (ep{m['expect_epoch']}, INTERIM)\n\n")
    md.append(f"> generated: {time.strftime('%Y-%m-%d %H:%M:%S')}  ·  "
              "`scripts/interim_eval.py --task report --which difficulty`  ·  "
              "protocol verbatim-replicated from `difficulty_eval.py`\n\n")
    md.append(f"> {INTERIM_NOTE}\n\n")
    md.append("> D0 = **this model's same-checkpoint, same-protocol full pool** test_eval (max aggregation, "
              "DA-H3 caliber: same checkpoint / same pool / same windowing-aggregation implementation); "
              "evo cache: M2 uses the original difficulty cache, M3 uses the seed42 key-permuted variant "
              "(build_shuffle_cache.py, same method as its training cache).\n\n")

    md.append("\n## 1. Difficulty-AUPRC curve (primary metric: max aggregation)\n\n")
    md.append("| tier | difficulty axis | n_contigs | n_windows | AUPRC | AUROC | "
              "ΔAUPRC vs D0 | DeLong 95% CI | evo hits |\n")
    md.append("|---|---|---|---|---|---|---|---|---|\n")
    if d0:
        md.append(f"| **D0** | this model's full test pool | {d0['n_contigs']:,} | "
                  f"{d0['n_windows']:,} | **{d0['auprc']:.4f}** | "
                  f"{d0['auroc']:.4f} | 0 |  -  (full pool) | all |\n")
    else:
        md.append("| **D0** | this model's full test pool | _MISSING_ (test step not completed) | | | | | | |\n")
    for r in rows:
        if r.get("missing"):
            md.append(f"| {r['tier']} | {r['axis']} | _MISSING_ | | | | | | |\n")
            continue
        dl = r["delong_max"]
        delta = f"{r['auprc_max']-d0['auprc']:+.4f}" if d0 else " — "
        md.append(f"| **{r['tier']}** | {r['axis']} | {r['n_contigs']:,} | "
                  f"{r['n_windows']:,} | **{r['auprc_max']:.4f}** | "
                  f"{r['auroc_max']:.4f} | {delta} | "
                  f"[{dl['ci95'][0]:.4f}, {dl['ci95'][1]:.4f}] | "
                  f"{r['evo_hit']}/{r['evo_total']} |\n")

    md.append("\n## 2. All aggregation calibers per tier\n\n")
    md.append("| tier | AUPRC(max) | AUPRC(mean) | AUPRC(top3) | F1@opt(max) | "
              "AUROC(max) | z vs 0.5 |\n|---|---|---|---|---|---|---|\n")
    if d0:
        md.append(f"| D0 | {d0['auprc']:.4f} | {d0['auprc_mean']:.4f} |  —  |  —  | "
                  f"{d0['auroc']:.4f} |  —  |\n")
    for r in rows:
        if r.get("missing"):
            md.append(f"| {r['tier']} | _MISSING_ | | | | | |\n")
            continue
        dl = r["delong_max"]
        md.append(f"| {r['tier']} | {r['auprc_max']:.4f} | {r['auprc_mean']:.4f} | "
                  f"{r['auprc_top3']:.4f} | {r['f1_max']:.4f} | "
                  f"{r['auroc_max']:.4f} | {dl['z_vs_half']:+.2f} |\n")

    md.append("\n## 3. Generation acceptance check (island span)\n\n")
    md.append("| tier | n_pos | span p50 | span p90 | IV4 reference |\n|---|---|---|---|---|\n")
    for r in rows:
        if r.get("missing") or not r.get("span") or "error" in r.get("span", {}):
            md.append(f"| {r['tier']} |  —  | | | p50=8,019 / p90=28,155 |\n")
            continue
        s = r["span"]
        md.append(f"| {r['tier']} | {s.get('n_pos', ' — ')} | "
                  f"{s.get('span_p50', 0):.0f} | {s.get('span_p90', 0):.0f} | "
                  f"p50=8,019 / p90=28,155 |\n")

    md.append("\n## 4. Comparability notes\n\n")
    md.append("- All three tiers use seed=42 + genome_isolation proportions identical to D0 → the test genome pool is "
              "consistent with Contig_500k; each tier varies exactly one difficulty axis; n_pos=n_neg=5000.\n"
              "- D3 has far fewer windows (fragmentation → shorter contigs) → max aggregation carries a mechanistic "
              "window-count effect (already noted in the M0 version); the D3 reference numbers should be read alongside the window count.\n"
              "- M0 ep2 curve: see docs/evidence/DIFFICULTY_CURVE_M0.md (use_evo=False;"
              " this M2/M3 run is a use_evo=True control).\n")
    with open(out_dir / "difficulty.md", "w") as f:
        f.write("".join(md))
    print(f"[Report] saved {out_dir}/difficulty.md")


