    md.append(f"> **{m['header']}**\n\n")
    md.append(f"# Four real anchors  -  {m['name']} (ep{m['expect_epoch']}, INTERIM)\n\n")
    md.append(f"> generated: {time.strftime('%Y-%m-%d %H:%M:%S')}  ·  "
              "`scripts/interim_eval.py --task report --which anchors`\n\n")
    md.append(f"> {INTERIM_NOTE}\n\n")
