    hint = ("(M3: the chain must first run build_shuffle_cache.py to generate test_shuffled.pt)"
            if m["tag"] == "m3ep3" else "(M2: evo_cache/difficulty should already be in place)")
    assert Path(evo_cache).is_file(), f"missing D-tier evo cache {evo_cache} {hint}"

    out_dir = Path(args.out_dir) if args.out_dir else m["out_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    tag = f"difficulty_{args.tier}_{m['tag']}"
    t_start = time.time()

    samples = read_tier_samples(test_dir, args.limit)
    model, contract_info, mc, device = load_model_interim(
        m["ckpt"], m["config"], m["expect_epoch"])
    import yaml as _yaml
    _dc = _yaml.safe_load(open(m["config"]))["data"]

    contig_windows, labels_map, n_windows, infer_s, evo_meta = \
        predict_windows_interim(
            model, samples, window=_dc["sw_window_size"],
            overlap=_dc["sw_overlap"], win_cap=args.win_cap,
            batch_size=args.batch, device=device, evo_cache_path=evo_cache)
    contract_info["evo_cache"] = evo_meta["evo_cache_path"]
    del model
    torch.cuda.empty_cache()

    results, wstats, sid_list, y_sorted, agg_scores, delong = \
        aggregate_all(contig_windows, labels_map)
    save_npz(out_dir, tag, sid_list, y_sorted, contig_windows, agg_scores)
    payload = {
        "tier": args.tier, "tier_dir": tier_dir, "difficulty_axis": axis,
        "model": m["name"], "interim_header": m["header"],
        "protocol": {
            "source": "difficulty_eval.py run_tier verbatim replication (interim driver)",
            "window_size": _dc["sw_window_size"], "overlap": _dc["sw_overlap"],
            "batch_size": args.batch, "max_eval_windows": args.win_cap,
            "aggregations": ["max", "mean", "median", "top3_mean"],
            "device": "cuda", "gpu": gpu_name, "dtype": "fp32",
            "evo_adaptation": "evo_cache_path passed in (not needed by the original M0 version, which had use_evo=False)",
        },
        "contract": contract_info, "evo": evo_meta, "window_stats": wstats,
        "delong": delong, "infer_seconds": infer_s,
        "total_seconds": time.time() - t_start, "results": results,
    }
    dump_json(out_dir, tag, payload)
    print(f"\n[{args.tier}] {axis}")
    for name in ["max", "mean", "median", "top3_mean"]:
        mm, d = results[name], delong[name]
        print(f"  [{name:9s}] AUC={mm.get('auc', float('nan')):.4f} "
              f"[{d['ci95'][0]:.4f},{d['ci95'][1]:.4f}] | "
              f"AUPRC={mm.get('auprc', float('nan')):.4f}")
    print(f"Saved: {out_dir}/{tag}.json + .npz")


