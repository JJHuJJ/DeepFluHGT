def assert_4090():
    n = torch.cuda.device_count()
    assert n == 1, f"exactly 1 visible GPU expected (4090 GPU lock), actual {n}"
    name = torch.cuda.get_device_name(0)
    assert "4090" in name, f"visible GPU is not RTX 4090: {name}"
    free, total = torch.cuda.mem_get_info(0)
    print(f"[GPU] {name} | mem free {free/1e9:.1f}/{total/1e9:.1f} GB | "
          f"CUDA {torch.version.cuda} | torch {torch.__version__}")
    return name


# ═══════════════════════════════════════════════════════════════════════════ #
#  model construction (GPU version; protocol fields consistent with cpu.load_model_cpu)
# ═══════════════════════════════════════════════════════════════════════════ #

def load_model_gpu(ckpt: Path, config: Path):
    import yaml
    from model.api import build_model
    from model.contracts import HGTConfig

    device = torch.device("cuda:0")
    mc = yaml.safe_load(open(config))["model"]
    cfg = HGTConfig(
        data_mode="contig", max_contig_length=3000,
        hidden_dim=mc["hidden_dim"],
        num_attention_heads=mc["num_attention_heads"],
        dropout=mc["dropout"],
        graph_top_k=mc["graph_top_k"],
        bio_feature_dim=mc["bio_feature_dim"],
        pretrained_nt_path=mc.get("pretrained_nt_path", str(NT_FALLBACK)),
        pretrained_caduceus_path="",
        use_local_encoder=False,
        use_evo=bool(mc.get("use_evo", False)),
        pretrained_evo_dim=int(mc.get("pretrained_evo_dim", 4096)),
        early_exit_threshold=0.95,
    )
    model = build_model(cfg)

    st = torch.load(ckpt, map_location="cpu", weights_only=False)
    ckpt_epoch = st.get("epoch")
    contract = st.get("contract", {})
    if ckpt_epoch != 2:  # same rule as the CPU version: best_model must be ep2, else roll back to the archive
        alt = ckpt.parent / "epoch_2.pt"
        print(f"[WARN] {ckpt.name} epoch={ckpt_epoch} ≠ 2 → fallback {alt.name}")
        st = torch.load(alt, map_location="cpu", weights_only=False)
        ckpt_epoch = st.get("epoch")
        contract = st.get("contract", {})
    missing, unexpected = model.load_state_dict(st["model"], strict=False)
    model.to(device).eval()

    contract_info = {
        "ckpt": str(ckpt),
        "ckpt_epoch": ckpt_epoch,
        "encoder_frozen": contract.get("encoder_frozen"),
        "backbone_sha256": contract.get("backbone_sha256"),
        "config_sha256": contract.get("config_sha256"),
        "dataset_manifest_sha256": contract.get("dataset_manifest_sha256"),
        "state_dict_missing": len(missing),
        "state_dict_unexpected": len(unexpected),
    }
    assert contract.get("encoder_frozen") is True, "contract: encoder_frozen must be True"
    assert contract.get("backbone_sha256"), "contract: backbone_sha256 missing"
    print(f"[Model] epoch={ckpt_epoch} load: missing={len(missing)} "
          f"unexpected={len(unexpected)} → {device}")
    print(f"[Contract] encoder_frozen={contract_info['encoder_frozen']} "
          f"backbone_sha256={contract_info['backbone_sha256'][:16]}...")
    return model, contract_info, mc, device


# ═══════════════════════════════════════════════════════════════════════════ #
#  window prediction (GPU; windowing/dataset identical to the CPU version, batch>1)
# ═══════════════════════════════════════════════════════════════════════════ #

def predict_windows_gpu(model, samples: dict, window: int, overlap: int,
                        win_cap: int, batch_size: int, device):
    from torch.utils.data import DataLoader
    from data_pipeline.impl.dataset import SlidingWindowContigDataset
    from data_pipeline.impl.collator import HGTCollator
    from data_pipeline.contracts import HGTSample

    hgt_samples, labels_map = [], {}
    for sid, (label, seq) in samples.items():
        hgt_samples.append(HGTSample(
            seq_id=sid, label=label, sequence=seq, r2_sequence=None,
            events=[], sample_type="POS" if label == 1 else "NEG",
            seq_len=len(seq)))
        labels_map[sid] = label

    ds = SlidingWindowContigDataset(
        samples=hgt_samples, window_size=window, overlap=overlap,
        is_training=False, max_neg_windows=9999, max_eval_windows=win_cap,
        extract_bio=True)
    loader = DataLoader(ds, batch_size=batch_size, shuffle=False,
                        collate_fn=HGTCollator(pad_id=0), num_workers=4)
    print(f"[Data] {len(hgt_samples)} contigs, {len(ds)} windows "
          f"(win_cap={win_cap}, batch={batch_size})")

    contig_windows = defaultdict(list)
    t0 = time.time()
    with torch.no_grad():
        for i, batch in enumerate(loader):
            batch = batch.to(device)
            output = model(batch, early_exit=False)
            probs = torch.sigmoid(output.cls_logits.squeeze(-1)).float().cpu().numpy()
            sids = batch.original_seq_ids or batch.seq_ids
            for sid, p in zip(sids, probs):
                contig_windows[sid].append(float(p))
            if (i + 1) % 50 == 0:
                el = time.time() - t0
                done = (i + 1) * batch_size
                print(f"  [{min(done,len(ds))}/{len(ds)}] {el:.0f}s "
                      f"({el/(i+1):.2f}s/batch, "
                      f"ETA {(len(loader)-i-1)*el/(i+1)/60:.1f}min)", flush=True)
    infer_s = time.time() - t0
    print(f"[Predict] {len(ds)} windows in {infer_s:.0f}s "
          f"({infer_s/max(1,len(ds)):.3f}s/win)")
    return contig_windows, labels_map, len(ds), infer_s


# ═══════════════════════════════════════════════════════════════════════════ #
#  per-anchor DeLong (single predictor: var_a → SE / CI / z-vs-0.5)
# ═══════════════════════════════════════════════════════════════════════════ #

def delong_single(y: np.ndarray, scores: np.ndarray) -> dict:
    import math
    r = delong_test_full(y, scores, scores)   # var_a = single-predictor AUC variance
    se = math.sqrt(r["var_a"])
    auc = r["auc_a"]
    z = (auc - 0.5) / se if se > 0 else math.inf
    p = math.erfc(abs(z) / math.sqrt(2.0))
    return {"auc": auc, "se": se, "ci95": [auc - 1.959963984540054 * se,
                                           auc + 1.959963984540054 * se],
            "z_vs_half": z, "p_vs_half": p, "n": int(len(y)),
            "n_pos": int(np.sum(y == 1)), "var": r["var_a"]}


# ═══════════════════════════════════════════════════════════════════════════ #
#  Philympics paired analysis (replicating the core of v6.8 analyze_v5_4.py:
#  event-level AUROC + paired bootstrap 10k + species bootstrap + LOSO + shortcut correlations)
# ═══════════════════════════════════════════════════════════════════════════ #

def philympics_paired_analysis(contig_windows, labels_map, match_stats):
    from sklearn.metrics import roc_auc_score

    # paired: events in matching_stats with control_len>0, in prophage order ↔ control order
    valid = [i for i, m in enumerate(match_stats) if m.get("control_len", 0) > 0]
    p_ids = [m["prophage_id"] for m in match_stats if m.get("control_len", 0) > 0]
    c_ids = [m["control_id"] for m in match_stats if m.get("control_len", 0) > 0]
    assert len(p_ids) == len(c_ids) == len(valid)
    for pid in p_ids + c_ids:
        assert pid in contig_windows, f"missing contig score: {pid}"
    species = [match_stats[i]["org"] for i in valid]

    out = {"n_pairs": len(valid), "n_species": len(set(species)),
           "per_agg": {}, "wins": {}, "species_bootstrap": {}, "loso": {},
           "shortcut": {}}

    def agg(sid, kind):
        w = contig_windows[sid]
        if kind == "max":
            return max(w)
        if kind == "mean":
            return float(np.mean(w))
        return float(np.mean(sorted(w, reverse=True)[:3]))

    y2 = np.concatenate([np.ones(len(valid)), np.zeros(len(valid))])
    rng = np.random.RandomState(42)
    by_sp = defaultdict(list)
    for i, sp in enumerate(species):
        by_sp[sp].append(i)

    for kind in ["max", "mean", "top3_mean"]:
        ps = np.array([agg(s, kind) for s in p_ids])
        cs = np.array([agg(s, kind) for s in c_ids])
        s2 = np.concatenate([ps, cs])
        auc = float(roc_auc_score(y2, s2))
        # B7-1 (2026-10-04): pair-preserving bootstrap. Resample PAIR indices and
        # rebuild the pooled arrays, instead of resampling concatenated units i.i.d.
        # (which destroys prophage-control pairing). Diagnosis and validated
        # recompute: B3_PHILYMPICS_PAIRED_FIX (2026-09-29). Seed/B unchanged (42/10k).
        n_pairs = len(ps)
        boot = []
        for _ in range(10000):
            pi = rng.randint(0, n_pairs, n_pairs)
            yb = np.concatenate([np.ones(n_pairs), np.zeros(n_pairs)])
            sb = np.concatenate([ps[pi], cs[pi]])
            if len(set(yb)) < 2:
                continue
            boot.append(roc_auc_score(yb, sb))
        boot = np.array(boot)
        out["per_agg"][kind] = {"auroc": auc, "ci95": [
            float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]}
        out["wins"][kind] = int(sum(1 for i in range(len(valid)) if ps[i] > cs[i]))

    # species bootstrap (mean aggregation, 8 §3)
    sp_rng = np.random.RandomState(42)
    boot_mean = []
    for _ in range(10000):
        sampled = [sp_rng.choice(list(by_sp.keys())) for _ in range(len(by_sp))]
        idx = []
        for sp in sampled:
            idx.extend(by_sp[sp])
        if len(idx) < 4:
            continue
        yb = np.concatenate([np.ones(len(idx)), np.zeros(len(idx))])
        sb = np.concatenate([[agg(p_ids[i], "mean") for i in idx],
                             [agg(c_ids[i], "mean") for i in idx]])
        boot_mean.append(roc_auc_score(yb, sb))
    bm = np.array(boot_mean)
    out["species_bootstrap"]["mean"] = {
        "median": float(np.median(bm)), "iqr": [float(np.percentile(bm, 25)),
                                                float(np.percentile(bm, 75))],
        "p_gt_05": float(np.mean(bm > 0.5)), "p_gt_06": float(np.mean(bm > 0.6))}

    # LOSO (mean aggregation, 8 §4)
    for sp in sorted(set(species)):
        keep = [i for i in range(len(valid)) if species[i] != sp]
        if len(keep) < 4:
            continue
        yb = np.concatenate([np.ones(len(keep)), np.zeros(len(keep))])
        sb = np.concatenate([[agg(p_ids[i], "mean") for i in keep],
                             [agg(c_ids[i], "mean") for i in keep]])
        out["loso"][sp] = float(roc_auc_score(yb, sb))

    # shortcut correlations (max score vs GC / log10 len, 8 §5)
    gc = np.array([match_stats[i]["prophage_gc"] for i in valid])
    ln = np.array([match_stats[i]["prophage_len"] for i in valid])
    p_max = np.array([agg(s, "max") for s in p_ids])
    out["shortcut"] = {"corr_max_gc": float(np.corrcoef(p_max, gc)[0, 1]),
                       "corr_max_loglen": float(np.corrcoef(p_max, np.log10(ln))[0, 1])}
    return out


# ═══════════════════════════════════════════════════════════════════════════ #

def read_paired_philympics(fasta_path):
    """>prophage_...=1 / >control_...=0 → {sid: (label, seq)} + ordered id list."""
    samples, order, cur, buf = {}, [], None, []
    for ln in open(fasta_path):
        ln = ln.strip()
        if ln.startswith(">"):
            if cur is not None:
                samples[cur] = "".join(buf)
            cur = ln[1:].split()[0]
            order.append(cur)
            buf = []
        else:
            buf.append(ln.upper())
    if cur is not None:
        samples[cur] = "".join(buf)
    out = {}
    for sid in order:
        label = 1 if sid.startswith("prophage_") else 0
        out[sid] = (label, samples[sid])
    n_pos = sum(v[0] for v in out.values())
    print(f"[Philympics] {len(out)} sequences: {n_pos} prophage + "
          f"{len(out)-n_pos} control")
    return out


def main():
    gpu_name = assert_4090()
    args = ARGS
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tag = f"real_anchor_{args.anchor}_{args.tag}"
    t_start = time.time()

    # ── 1. data (reuse the CPU version's construction; ICE negatives regenerated with the same seed=42, consistent with the CPU npz) ──
    neg_meta, phil_stats = None, None
    if args.anchor == "benbow":
        samples = cpu.read_benbow(cpu.BENBOW_FASTA)
        n_pos = sum(1 for _, (l, _) in samples.items() if l == 1)
        print(f"[Benbow] {len(samples)} samples: {n_pos} pos + {len(samples)-n_pos} neg")
    elif args.anchor == "iv4":
        samples = cpu.build_iv4_300_300(cpu.IV4_DIR)
    elif args.anchor == "ice":
        ice = cpu.read_iceberg(cpu.ICE_FASTA)
        print(f"[ICE] experimental ICE records: {len(ice)}")
        samples, neg_meta = cpu.build_ice_anchor(ice, cpu.IV4_DIR, n_neg=len(ice))
        # cross-check against the CPU version's npz: the negative count must match (same seed, deterministic)
        ref = np.load(out_dir / "real_anchor_ice_m0ep2.npz", allow_pickle=True)
        ref_neg = int((ref["labels"] == 0).sum())
        assert ref_neg == sum(1 for v in samples.values() if v[0] == 0), \
            f"ICE negative count inconsistent with the CPU npz: {ref_neg} vs newly generated"
        print(f"[ICE] negative cross-check: consistent with real_anchor_ice_m0ep2.npz ({ref_neg} items)")
    else:
        assert PHIL_PAIRED.exists(), \
            f"{PHIL_PAIRED} does not exist  —  run scripts/build_philympics_anchor.py first"
        samples = read_paired_philympics(PHIL_PAIRED)
        phil_stats = json.load(open(PHIL_STATS))

    if args.limit > 0:
        pos = {k: v for k, v in samples.items() if v[0] == 1}
        neg = {k: v for k, v in samples.items() if v[0] == 0}
        samples = dict(list(pos.items())[:args.limit])
        samples.update(dict(list(neg.items())[:args.limit]))
        print(f"[Smoke] limited to {len(samples)} contigs")

    # ── 2. model + inference ──
    model, contract_info, mc, device = load_model_gpu(Path(args.ckpt), Path(args.config))
    import yaml as _yaml
    _dc = _yaml.safe_load(open(args.config))["data"]

    contig_windows, labels_map, n_windows, infer_s = predict_windows_gpu(
        model, samples, window=_dc["sw_window_size"], overlap=_dc["sw_overlap"],
        win_cap=args.win_cap, batch_size=args.batch, device=device)

    # release the GPU (subsequent aggregation/statistics are pure CPU)
    del model
    torch.cuda.empty_cache()

    # ── 3. aggregation + metrics + DeLong (CPU-version aggregation reused verbatim) ──
    results = cpu.aggregate_and_eval(contig_windows, labels_map)
    wstats = cpu.window_stats(contig_windows, labels_map)

    sid_list = sorted(contig_windows.keys())
    y_sorted = np.array([labels_map[s] for s in sid_list], dtype=np.int64)

    def _agg(kind, w):
        if kind == "max":
            return max(w)
        if kind == "mean":
            return float(np.mean(w))
        if kind == "median":
            return float(np.median(w))
        return float(np.mean(sorted(w, reverse=True)[:3]))

    agg_scores = {k: np.array([_agg(k, contig_windows[s]) for s in sid_list],
                              dtype=np.float32)
                  for k in ["max", "mean", "median", "top3_mean"]}
    delong = {k: delong_single(y_sorted, v) for k, v in agg_scores.items()}

    # ── 4. Philympics paired analysis ──
    phil = None
    if args.anchor == "philympics" and args.limit == 0:
        phil = philympics_paired_analysis(contig_windows, labels_map, phil_stats)

    # ── 5. save artifacts ──
    np.savez(
        out_dir / f"{tag}.npz",
        contig_ids=np.array(sid_list, dtype=object),
        labels=y_sorted,
        n_windows=np.array([len(contig_windows[s]) for s in sid_list], dtype=np.int64),
        window_probs=np.array([np.asarray(contig_windows[s], dtype=np.float32)
                               for s in sid_list], dtype=object),
        **{f"agg_{k}": v for k, v in agg_scores.items()},
    )

    payload = {
        "anchor": args.anchor,
        "protocol": {
            "source": "replication of v6.8 scripts/eval_external_benbow.py (GPU version)",
            "window_size": 3000, "overlap": 300,
            "batch_size": args.batch,
            "max_eval_windows_config_v68": 10,
            "max_eval_windows_used": args.win_cap,
            "aggregations": ["max", "mean", "median", "top3_mean"],
            "device": "cuda", "gpu": gpu_name,
            "dtype": "fp32",
            "note": "full v6.8 protocol (win_cap=10); the CPU probe version's 4/3 window discount is cancelled",
        },
        "contract": contract_info,
        "window_stats": wstats,
        "neg_sample_meta": neg_meta,
        "delong": delong,
        "philympics_paired": phil,
        "infer_seconds": infer_s,
        "total_seconds": time.time() - t_start,
        "results": results,
    }
    with open(out_dir / f"{tag}.json", "w") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False,
                  default=lambda o: float(o) if isinstance(o, (np.floating,)) else o)

    print(f"\n{'='*70}")
    print(f"[{args.anchor.upper()}] n={wstats['n_contigs']} "
          f"(pos={results['max']['n_positive']}/neg={results['max']['n_negative']}) "
          f"windows={wstats['n_windows']}")
    for name in ["max", "mean", "median", "top3_mean"]:
        m = results[name]
        d = delong[name]
        print(f"  [{name:9s}] AUC={m.get('auc', float('nan')):.4f} "
              f"[{d['ci95'][0]:.4f},{d['ci95'][1]:.4f}] "
              f"z={d['z_vs_half']:+.2f} p={d['p_vs_half']:.2e} | "
              f"AUPRC={m.get('auprc', float('nan')):.4f} "
              f"F1@opt({m.get('optimal_threshold', 0):.2f})="
              f"{m.get('f1_at_optimal', float('nan')):.4f}")
    if phil:
        for kind, v in phil["per_agg"].items():
            print(f"  [paired {kind}] AUROC={v['auroc']:.4f} "
                  f"[{v['ci95'][0]:.4f},{v['ci95'][1]:.4f}] "
                  f"wins={phil['wins'][kind]}/{phil['n_pairs']}")
        print(f"  species bootstrap P(>0.5)={phil['species_bootstrap']['mean']['p_gt_05']:.1%}")
    print(f"  infer={infer_s/60:.1f}min total={(time.time()-t_start)/60:.1f}min")
    print(f"Saved: {out_dir}/{tag}.json + .npz")


if __name__ == "__main__":
    main()
